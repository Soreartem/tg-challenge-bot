function getPromptForDay(day) {
  const idx = Math.max(0, (day - 1) % 100);
  const scene = IMAGE_SCENES[idx % IMAGE_SCENES.length];
  const style = IMAGE_STYLES[Math.floor(idx / IMAGE_SCENES.length) % IMAGE_STYLES.length];
  return `${scene}, ${style}, day ${day} edition`;
}

function getMessageText(day) {
  const idx = Math.max(0, Math.min(99, day - 1));
  const quote = QUOTES_100[idx];
  const joke = JOKES_100[idx];
  const hours = day * 24;
  const money = (day * 350).toLocaleString('ru-RU');

  const msk = getMoscowDate();
  const dayOfWeek = msk.getDay();
  let weekendBlock = '';
  if (dayOfWeek === 5 || dayOfWeek === 6) {
    weekendBlock = `\n⚠️ *Пятница/Суббота — режим повышенной брони!* Пока слабые сливают прогресс в стакан, ты держишь строй.`;
  }

  return [
    `🔥 *ЧЕЛЛЕНДЖ 100 ДНЕЙ: ДЕНЬ ${day}* 🔥`,
    `${progressBar(day)}`,
    `⏱ На счетчике: *${duration(day)}* (*${hours} ч.* без алко)`,
    ``,
    `💪 *Факт и настрой дня:*`,
    `_${quote}_`,
    ``,
    `😂 *Прикол дня #${day}:*`,
    `${joke}`,
    weekendBlock,
    ``,
    `💰 В плюсе по бабкам: ~*${money} ₽*`,
    `Ни шагу назад. Газуем дальше! ✊`
  ].filter(Boolean).join('\n');
}

async function fetchImageBuffer(day) {
  const prompt = encodeURIComponent(getPromptForDay(day));
  const seed = day * 2026 + 777;
  const aiUrl = `https://image.pollinations.ai/prompt/${prompt}?width=1024&height=1024&nologo=true&seed=${seed}`;

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 18000);
    const res = await fetch(aiUrl, { signal: controller.signal });
    clearTimeout(timeout);
    if (res.ok) return Buffer.from(await res.arrayBuffer());
  } catch (e) {
    console.log('ИИ-генератор долго отвечает, беру запасное фото...');
  }

  try {
    const fallbackUrl = FALLBACK_PHOTOS[day % FALLBACK_PHOTOS.length];
    const res = await fetch(fallbackUrl);
    if (res.ok) return Buffer.from(await res.arrayBuffer());
  } catch (e) {}

  return null;
}

