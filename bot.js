// ---------- Точное Московское время (UTC+3) ----------
function getMoscowDate() {
  const now = new Date();
  const utcMs = now.getTime() + (now.getTimezoneOffset() * 60000);
  return new Date(utcMs + (3 * 3600 * 1000));
}

function dayCount() {
  const msk = getMoscowDate();
  const mskMidnight = Date.UTC(msk.getFullYear(), msk.getMonth(), msk.getDate());
  const startMidnight = Date.UTC(START_YEAR, START_MONTH, START_DAY);
  return Math.max(1, Math.floor((mskMidnight - startMidnight) / DAY_MS));
}

// ---------- Склонения и правильный подсчет срока ----------
function ru(n, one, few, many) {
  const n10 = n % 10;
  const n100 = n % 100;
  if (n100 > 4 && n100 < 20) return n + ' ' + many;
  if (n10 === 1) return n + ' ' + one;
  if (n10 >= 2 && n10 <= 4) return n + ' ' + few;
  return n + ' ' + many;
}

function duration(day) {
  const months = Math.floor(day / 30);
  const remAfterMonths = day % 30;
  const weeks = Math.floor(remAfterMonths / 7);
  const days = remAfterMonths % 7;
  const parts = [
    months ? ru(months, 'месяц', 'месяца', 'месяцев') : '',
    weeks ? ru(weeks, 'неделя', 'недели', 'недель') : '',
    days ? ru(days, 'день', 'дня', 'дней') : '',
  ].filter(Boolean);
  return parts.length ? parts.join(' и ') : '0 дней';
}

function progressBar(day) {
  const pct = Math.min(100, Math.round((day / DAY_LIMIT) * 100));
  const filled = Math.min(10, Math.round(pct / 10));
  const empty = 10 - filled;
  return `${'🟩'.repeat(filled)}${'⬜'.repeat(empty)} ${day}/${DAY_LIMIT} (${pct}%)`;
}

